#!/usr/bin/env python3
"""Emit src/rubik/rubik_tables.S, the tables of rubik_solve_asm.

The source is src/rubik/rubik_tables.h, the tables of the C version. The
assembly uses the same search, so the content is the same, laid out so that
one lookup is an add and a load:

  rubik_asm_perm  [3][5040] half  next p, stored as 2p (a byte offset)
  rubik_asm_ori   [3][729]  half  next o, stored as o
  rubik_asm_pair  [3][441]  word  next q, stored as 4q (a byte offset)
  rubik_asm_info  [441]     half pair: 729 * pair_pos[q], 5040 * pair_twist[q]
  rubik_asm_dist  [49][729] byte  D transposed: D[pos][o] = d_tab[o * 49 + pos]
  rubik_asm_perm_dist [9][5040] byte  G transposed: G[tw][p] = g_tab[p * 9 + tw]
  rubik_asm_rows  [3][3]    word  row addresses of the three move tables

Usage: mytests/gen_rubik_tables.py [header] [output]
"""

import re
import sys


def arrays(text):
    out = {}
    for m in re.finditer(r"static const uint(?:8|16)_t (\w+)(?:\[\d+\])+ = \{(.*?)\};", text, re.S):
        out[m.group(1)] = [int(x) for x in re.findall(r"\d+", m.group(2))]
    return out


def emit(f, directive, values, per_line=16):
    for i in range(0, len(values), per_line):
        f.write(f"    {directive} " + ", ".join(str(v) for v in values[i:i + per_line]) + "\n")


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "src/rubik/rubik_tables.h"
    dst = sys.argv[2] if len(sys.argv) > 2 else "src/rubik/rubik_tables.S"
    with open(src) as f:
        t = arrays(f.read())
    perm, ori, pair = t["perm_move"], t["ori_move"], t["pair_move"]
    d_tab, g_tab = t["d_tab"], t["g_tab"]
    pos, tw = t["pair_pos"], t["pair_twist"]
    assert len(perm) == 3 * 5040 and len(ori) == 3 * 729 and len(pair) == 3 * 441
    assert len(d_tab) == 729 * 49 and len(g_tab) == 5040 * 9
    assert len(pos) == 441 and len(tw) == 441

    with open(dst, "w") as f:
        f.write("# rubik_tables.S: tables of rubik_solve_asm, generated by\n"
                "# mytests/gen_rubik_tables.py from rubik_tables.h; do not edit.\n\n"
                "    .section .rodata\n")

        def label(name, align):
            f.write(f"\n    .globl  {name}\n    .p2align {align}\n{name}:\n")

        label("rubik_asm_rows", 2)
        for face in range(3):
            f.write(f"    .word   rubik_asm_perm + {face * 5040 * 2}, "
                    f"rubik_asm_ori + {face * 729 * 2}, "
                    f"rubik_asm_pair + {face * 441 * 4}\n")
        label("rubik_asm_pair", 2)
        emit(f, ".word", [4 * v for v in pair])
        label("rubik_asm_info", 1)
        info = []
        for q in range(441):
            info += [729 * pos[q], 5040 * tw[q]]
        emit(f, ".half", info)
        label("rubik_asm_perm", 1)
        emit(f, ".half", [2 * v for v in perm])
        label("rubik_asm_ori", 1)
        emit(f, ".half", ori)
        label("rubik_asm_dist", 0)
        emit(f, ".byte", [d_tab[o * 49 + p] for p in range(49) for o in range(729)], 32)
        label("rubik_asm_perm_dist", 0)
        emit(f, ".byte", [g_tab[p * 9 + w] for w in range(9) for p in range(5040)], 32)


if __name__ == "__main__":
    main()
